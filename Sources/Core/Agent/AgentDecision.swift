// AgentDecision.swift
// OpenClip
//
// Value types shared by the voice agent: what the user asked for, how the orchestrator chose to
// handle it, and the scripts it may synthesize. Pure Foundation so routing stays unit-testable.
import Foundation

public struct AgentRequest: Sendable, Equatable {
    public let transcript: String
    /// Selected text at key-down; empty when nothing was selected.
    public let selectedText: String
    public let appBundleID: String?
    /// Prior instruction/result pairs when the hotkey is pressed while a result is still visible.
    public let history: [AgentTurn]

    public init(transcript: String, selectedText: String = "", appBundleID: String? = nil, history: [AgentTurn] = []) {
        self.transcript = transcript
        self.selectedText = selectedText
        self.appBundleID = appBundleID
        self.history = history
    }

    public var hasSelection: Bool {
        !selectedText.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty
    }
}

public struct AgentTurn: Sendable, Equatable, Codable {
    public let instruction: String
    public let result: String

    public init(instruction: String, result: String) {
        self.instruction = instruction
        self.result = result
    }
}

public enum ScriptLanguage: String, Sendable, Equatable, Codable, CaseIterable {
    case javascript
    case shell
    case applescript
}

public struct SynthesizedScript: Sendable, Equatable {
    public let language: ScriptLanguage
    public let code: String

    public init(language: ScriptLanguage, code: String) {
        self.language = language
        self.code = code
    }
}

/// How a synthesized script's or an answer's text reaches the user.
public enum AgentDelivery: String, Sendable, Equatable, Codable {
    /// Replace the selection (or insert at the caret) in the frontmost app.
    case replace
    /// Show in a result card with Copy / Insert.
    case card
    /// Side effect only (opened a URL, ran automation); confirm with a toast.
    case silent
}

public enum AgentDecision: Sendable, Equatable {
    case runAction(actionID: String)
    case synthesize(SynthesizedScript, delivery: AgentDelivery)
    /// Rewrite the selection in place with the AI provider using `instruction`.
    case rewrite(instruction: String)
    /// Answer a question; the text is generated by the AI provider and shown in a card.
    case answer(instruction: String)
    case clarify(question: String, options: [String])
}

public struct ActionDescriptor: Sendable, Equatable {
    public let id: String
    public let title: String
    public let keywords: [String]

    public init(id: String, title: String, keywords: [String] = []) {
        self.id = id
        self.title = title
        self.keywords = keywords
    }
}

public struct CommandMatch: Sendable, Equatable {
    public let actionID: String
    /// 0...1; 1 means the spoken command names the action exactly.
    public let score: Double

    public init(actionID: String, score: Double) {
        self.actionID = actionID
        self.score = score
    }
}

public enum AgentError: Error, Sendable, Equatable {
    case emptyTranscript
    case malformedDecision(String)
    case noCodeInResponse
    case scriptFailed(String)
}

extension AgentError: LocalizedError {
    public var errorDescription: String? {
        switch self {
        case .emptyTranscript: return String(localized: "Didn't catch that.")
        case .malformedDecision(let detail): return detail
        case .noCodeInResponse: return String(localized: "The AI reply contained no script.")
        case .scriptFailed(let message): return message
        }
    }
}
